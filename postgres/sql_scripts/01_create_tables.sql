-- ---------------------------------------------------------------- hard invariant
-- Original transactions are never updated or deleted (a ledger is corrected with new entries,
-- and changing an original amount would break the daily balance check). The generator also
-- enforces this in code; the trigger is the backstop.
CREATE OR REPLACE FUNCTION fin_trans_protect_original() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.data_origin = 'czech_original' THEN
        RAISE EXCEPTION 'fin_trans row % is czech_original and must never be % (insert a correcting entry instead)',
            OLD.trans_id, TG_OP;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER trg_fin_trans_protect_original
    BEFORE UPDATE OR DELETE ON fin_trans
    FOR EACH ROW EXECUTE FUNCTION fin_trans_protect_original();
