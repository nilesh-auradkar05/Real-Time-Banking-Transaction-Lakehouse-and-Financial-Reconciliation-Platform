-- Source schema for the banking CDC platform.
--
-- Not created here (they live in the Bronze/audit layers, not in this database): cdc_event,
-- dead_letter_event, load_batch, recon_run, recon_account_window, recon_exception.
--
-- Debezium: capture the fin_* tables (and optionally synthetic_*). Exclude replay_run and
-- replay_event; Airflow copies those to the audit schema separately.

-- ---------------------------------------------------------------- control tables
-- operation uses Debezium's letters in lower case: c (insert), u (update), d (delete).
CREATE TABLE IF NOT EXISTS replay_run (
    replay_run_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario       varchar(64),
    random_seed    bigint,
    speed_factor   numeric(10,2),
    started_at     timestamptz NOT NULL DEFAULT now(),
    ended_at       timestamptz,
    status         varchar(16) NOT NULL DEFAULT 'running'  -- running, completed, interrupted, failed
);

CREATE TABLE IF NOT EXISTS replay_event (
    replay_event_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    replay_run_id           bigint NOT NULL REFERENCES replay_run (replay_run_id),
    source_table            varchar(32) NOT NULL,
    record_pk               bigint NOT NULL,
    operation               char(1) NOT NULL CHECK (operation IN ('c', 'u', 'd')),
    data_origin             varchar(16) NOT NULL,
    business_date           date,
    amount                  numeric(12,2),
    intended_commit_at      timestamptz,
    actual_commit_at        timestamptz,   -- NULL = planned but not delivered
    injected_delay_seconds  int NOT NULL DEFAULT 0,
    injected_fault          varchar(32)
);
CREATE INDEX IF NOT EXISTS ix_replay_event_run ON replay_event (replay_run_id);
CREATE INDEX IF NOT EXISTS ix_replay_event_record ON replay_event (source_table, record_pk);

CREATE TABLE IF NOT EXISTS synthetic_batch (
    synthetic_batch_id    int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generator_version     varchar(32),
    faker_version         varchar(16),
    random_seed           bigint,
    locale                varchar(8),
    clients_created       int,
    accounts_created      int,
    transactions_created  int,
    business_date_from    date,
    business_date_to      date,
    created_at            timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- Czech tables
-- Types follow the Teradata DDL: BYTEINT -> smallint, DECIMAL -> numeric. Codes keep their
-- blank padding; cleanup happens in Silver.
-- Origin rule (CHECK): czech_original = id below 900,000,000 and no batch;
--                      faker_synthetic = id from 900,000,000 and a batch.
-- fin_card, fin_loan and fin_order have no batch column, so their CHECK ties id range to origin only.

CREATE TABLE IF NOT EXISTS fin_district (
    district_id                    smallint PRIMARY KEY,
    district_name                  varchar(19) NOT NULL UNIQUE,
    region                         varchar(15) NOT NULL,
    num_inhabitants                int,
    num_municipalities_gt499       smallint,
    num_municipalities_500to1999   smallint,
    num_municipalities_2000to9999  smallint,
    num_municipalities_gt10000     smallint,
    num_cities                     smallint,
    ratio_urban                    numeric(4,1),
    average_salary                 numeric(10,2),
    unemployment_rate95            numeric(3,2),   -- null for district 69
    unemployment_rate96            numeric(3,2),
    num_entrep_per1000             smallint,
    num_crimes95                   int,            -- null for district 69
    num_crimes96                   int
);

CREATE TABLE IF NOT EXISTS fin_client (
    client_id             int PRIMARY KEY,
    birth_date            date NOT NULL,
    gender                char(1) NOT NULL,
    district_id           smallint NOT NULL REFERENCES fin_district (district_id),
    synthetic_batch_id    int REFERENCES synthetic_batch (synthetic_batch_id),
    data_origin           varchar(16) NOT NULL,
    last_replay_event_id  bigint REFERENCES replay_event (replay_event_id),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fin_client_origin_ck CHECK (
        (data_origin = 'czech_original' AND synthetic_batch_id IS NULL AND client_id < 900000000)
        OR (data_origin = 'faker_synthetic' AND synthetic_batch_id IS NOT NULL AND client_id >= 900000000))
);

CREATE TABLE IF NOT EXISTS fin_account (
    account_id            int PRIMARY KEY,
    district_id           smallint NOT NULL REFERENCES fin_district (district_id),
    create_date           date NOT NULL,
    frequency             char(1) NOT NULL,        -- M monthly, W weekly, T after transaction
    synthetic_batch_id    int REFERENCES synthetic_batch (synthetic_batch_id),
    data_origin           varchar(16) NOT NULL,
    last_replay_event_id  bigint REFERENCES replay_event (replay_event_id),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fin_account_origin_ck CHECK (
        (data_origin = 'czech_original' AND synthetic_batch_id IS NULL AND account_id < 900000000)
        OR (data_origin = 'faker_synthetic' AND synthetic_batch_id IS NOT NULL AND account_id >= 900000000))
);

CREATE TABLE IF NOT EXISTS fin_disp (
    disp_id               int PRIMARY KEY,
    client_id             int NOT NULL REFERENCES fin_client (client_id),
    account_id            int NOT NULL REFERENCES fin_account (account_id),
    disp_type             char(1) NOT NULL,        -- O owner, D disponent
    synthetic_batch_id    int REFERENCES synthetic_batch (synthetic_batch_id),
    data_origin           varchar(16) NOT NULL,
    last_replay_event_id  bigint REFERENCES replay_event (replay_event_id),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fin_disp_origin_ck CHECK (
        (data_origin = 'czech_original' AND synthetic_batch_id IS NULL AND disp_id < 900000000)
        OR (data_origin = 'faker_synthetic' AND synthetic_batch_id IS NOT NULL AND disp_id >= 900000000))
);

CREATE TABLE IF NOT EXISTS fin_card (
    card_id               int PRIMARY KEY,
    disp_id               int NOT NULL REFERENCES fin_disp (disp_id),
    card_type             char(1) NOT NULL,
    issued_date           date NOT NULL,
    data_origin           varchar(16) NOT NULL,
    last_replay_event_id  bigint REFERENCES replay_event (replay_event_id),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fin_card_origin_ck CHECK (
        (data_origin = 'czech_original' AND card_id < 900000000)
        OR (data_origin = 'faker_synthetic' AND card_id >= 900000000))
);

CREATE TABLE IF NOT EXISTS fin_loan (
    loan_id               int PRIMARY KEY,
    account_id            int NOT NULL UNIQUE REFERENCES fin_account (account_id),
    granted_date          date NOT NULL,
    amount                numeric(12,2) NOT NULL,
    duration              smallint NOT NULL,
    payments              numeric(12,2) NOT NULL,
    status                char(1) NOT NULL,        -- A, B, C, D
    data_origin           varchar(16) NOT NULL,
    last_replay_event_id  bigint REFERENCES replay_event (replay_event_id),
