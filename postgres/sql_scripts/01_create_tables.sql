CREATE TABLE IF NOT EXISTS fin_order (
    order_id              int PRIMARY KEY,
    account_id            int NOT NULL REFERENCES fin_account (account_id),
    bank_to               char(2) NOT NULL,
    account_to            int NOT NULL,
    amount                numeric(12,2) NOT NULL,
    category              char(2),                 -- HH, IN, LO, LE or blank
