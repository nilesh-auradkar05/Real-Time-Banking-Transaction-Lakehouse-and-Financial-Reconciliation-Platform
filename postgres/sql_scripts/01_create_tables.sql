-- trans_date is the business date and is never overwritten. recorded_at is when the row
-- reached PostgreSQL. amount is signed (debits negative).
CREATE TABLE IF NOT EXISTS fin_trans (
    trans_id              int PRIMARY KEY,
    account_id            int NOT NULL REFERENCES fin_account (account_id),
    trans_date            date NOT NULL,
    amount                numeric(12,2) NOT NULL,
    balance               numeric(12,2) NOT NULL,
    trans_type            char(1) NOT NULL,        -- C credit, D debit, P pension-type debit
    operation             char(3),                 -- blank = interest credit
    category              char(2),
    other_bank_id         char(2),
    other_account_id      int,
    recorded_at           timestamptz NOT NULL DEFAULT now(),
    synthetic_batch_id    int REFERENCES synthetic_batch (synthetic_batch_id),
    data_origin           varchar(16) NOT NULL,
    last_replay_event_id  bigint REFERENCES replay_event (replay_event_id),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fin_trans_origin_ck CHECK (
        (data_origin = 'czech_original' AND synthetic_batch_id IS NULL AND trans_id < 900000000)
        OR (data_origin = 'faker_synthetic' AND synthetic_batch_id IS NOT NULL AND trans_id >= 900000000))
);
CREATE INDEX IF NOT EXISTS ix_fin_trans_account ON fin_trans (account_id);

