USE WAREHOUSE BANKING_ETL_WH;
USE DATABASE BANKING_LAKEHOUSE;

LIST @RAW.BANKING_CDC_STAGE PATTERN='.*[.]parquet';

SELECT SOURCE_TABLE, OP, COUNT(*) AS EVENT_COUNT, MIN(RAW_LOADED_AT) AS FIRST_LOADED,
    MAX(RAW_LOADED_AT) AS LAST_LOADED
FROM RAW.CDC_EVENTS GROUP BY 1,2 ORDER BY 1,2;

SELECT EVENT_ID, COUNT(*) AS COPIES
FROM RAW.CDC_EVENTS GROUP BY 1 HAVING COUNT(*) > 1 ORDER BY COPIES DESC LIMIT 25;

-- COPY_HISTORY CAN BE USED TO INPECT PER-FILE INGESTION ERROR AND LOAD STATUS
SELECT * FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(
    TABLE_NAME => 'RAW.CDC_EVENTS', START_TIME => DATEADD('day', -7, CURRENT_TIMESTAMP())))
ORDER BY LAST_LOAD_TIME DESC LIMIT 50;

SELECT TABLE_NAME, ROW_COUNT FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA IN ('SILVER', 'GOLD') ORDER BY TABLE_SCHEMA,TABLE_NAME;