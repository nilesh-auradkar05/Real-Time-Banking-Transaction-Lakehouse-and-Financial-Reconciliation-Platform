USE ROLE ACCOUNTADMIN;
USE WAREHOUSE BANKING_ETL_WH;
USE DATABASE BANKING_LAKEHOUSE;
USE SCHEMA RAW;

CREATE FILE FORMAT IF NOT EXISTS CDC_PARQUET_FMT
    TYPE = PARQUET USE_LOGICAL_TYPE = TRUE;

CREATE STAGE IF NOT EXISTS BANKING_CDC_STAGE
    URL = 's3://banking-landing/landing/cdc/'
    STORAGE_INTEGRATION = BANKING_S3_INTEGRATION
    FILE_FORMAT = CDC_PARQUET_FMT;

-- RAW is append-only. Snowflake COPY tracks loaded file names for this table.
-- Duplicate logical messages with different files are handled by dbt's transport dedup.

CREATE TABLE IF NOT EXISTS RAW.CDC_EVENTS(
    EVENT_ID VARCHAR,
    TOPIC VARCHAR,
    KAFKA_PARTITION NUMBER(10,0),
    KAFKA_OFFSET NUMBER(38,0),
    KAFKA_TIMESTAMP_MS NUMBER(38,0),
    SOURCE_DATABASE VARCHAR,
    SOURCE_SCHEMA VARCHAR,
    SOURCE_TABLE VARCHAR,
    OP VARCHAR,
    RECORD_PK NUMBER(38,0),
    REPLAY_EVENT_ID NUMBER(38,0),
    DATA_ORIGIN VARCHAR,
    SYNTHETIC_BATCH_ID NUMBER(38,0),
    EVENT_TS_MS NUMBER(38,0),
    DEBEZIUM_TS_MS NUMBER(38,0),
    SOURCE_LSN VARCHAR,
    SOURCE_TXID VARCHAR,
    SNAPSHOT VARCHAR,
    KEY_JSON VARIANT,
    BEFORE_JSON VARIANT,
    AFTER_JSON VARIANT,
    SOURCE_JSON VARIANT,
    PAYLOAD_JSON VARIANT,
    LANDING_INGESTED_AT VARCHAR,
    SRC_FILENAME VARCHAR,
    SRC_FILE_ROW_NUMBER NUMBER(38,0),
    RAW_LOADED_AT TIMESTAMP_TZ
);