Use role accountadmin;

CREATE WAREHOUSE IF NOT EXISTS BANKING_ETL_WH WAREHOUSE_SIZE='XSMALL'
    AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;

CREATE DATABASE IF NOT EXISTS BANKING_LAKEHOUSE;
CREATE SCHEMA IF NOT EXISTS BANKING_LAKEHOUSE.RAW;
CREATE SCHEMA IF NOT EXISTS BANKING_LAKEHOUSE.SILVER;
CREATE SCHEMA IF NOT EXISTS BANKING_LAKEHOUSE.GOLD;
CREATE SCHEMA IF NOT EXISTS BANKING_LAKEHOUSE.AUDIT;

CREATE ROLE IF NOT EXISTS FINANCE_DBT_ROLE;
GRANT USAGE   ON WAREHOUSE BANKING_ETL_WH                     TO ROLE FINANCE_DBT_ROLE;
GRANT OPERATE ON WAREHOUSE BANKING_ETL_WH                     TO ROLE FINANCE_DBT_ROLE;
GRANT ALL     ON DATABASE BANKING_LAKEHOUSE                   TO ROLE FINANCE_DBT_ROLE;
GRANT ALL     ON ALL SCHEMAS IN DATABASE BANKING_LAKEHOUSE    TO ROLE FINANCE_DBT_ROLE;
GRANT ALL     ON FUTURE SCHEMAS IN DATABASE BANKING_LAKEHOUSE TO ROLE FINANCE_DBT_ROLE;
GRANT ALL     ON FUTURE TABLES IN DATABASE BANKING_LAKEHOUSE  TO ROLE FINANCE_DBT_ROLE;
GRANT ALL     ON FUTURE VIEWS IN DATABASE BANKING_LAKEHOUSE   TO ROLE FINANCE_DBT_ROLE;

SET my_user = CURRENT_USER();
GRANT ROLE FINANCE_DBT_ROLE TO USER IDENTIFIER($my_user);